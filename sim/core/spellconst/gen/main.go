// Command gen turns a data-lane spellconst file into the per-rank Go
// arrays an ability file reads, in the shape sim/mage/frostbolt.go
// already uses. A Forever patch that changes a number is then a pipeline
// run and a `make spellconst`, not a code edit.
//
//	go run ./sim/core/spellconst/gen \
//	  -in  ../forever/data/builds/1.60.1.69893/spellconst/warrior.json \
//	  -out sim/warrior/constants_auto_gen.go \
//	  -package warrior
//
// A spell rank can carry several effects (Bloodthirst's rank 4, spell
// id 23894, has three: a direct-damage effect, a second damage
// component, and a rage-generation aura). The per-rank arrays this
// command emits — BaseDamage and SpellCoeff among them — describe one
// effect per rank, so it prefers that rank's school-damage effect
// (effect type 2) as its primary one, falling back to the first effect
// in the client's own order when there is no school-damage effect; the
// full effect list stays available from spellconst.Load for anything
// that needs the rest.
//
// The client also frequently lists two spell ids under the same
// (name, rank) pair — an old id and a newer reissue, or a player-cast
// version and a free/NPC-cast variant (Battle Shout rank 6 is both
// 11551 and 27578). Every array is indexed by the rank label itself,
// never by position, and a same-rank collision is resolved
// deterministically: the higher spell_level wins, ties broken by the
// higher id; every id that loses is named in a comment beside the array.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/wowsims/classic/sim/core/spellconst"
)

func main() {
	in := flag.String("in", "", "the data lane's spellconst/<class>.json")
	out := flag.String("out", "", "the Go file to write")
	pkg := flag.String("package", "", "the Go package name, e.g. warrior")
	flag.Parse()
	if *in == "" || *out == "" || *pkg == "" {
		log.Fatal("-in, -out and -package are all required")
	}

	class, err := spellconst.Load(*in)
	if err != nil {
		log.Fatal(err)
	}

	src, err := generate(class, filepath.Dir(*out), filepath.Base(*out), *pkg, *in)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s, build %s", *out, class.Build)
}

// generate produces the full contents of one class's constants_auto_gen.go.
// It takes no other input than class and the package's existing
// declarations (read from outDir, skipping outFile itself), so calling
// it twice against the same class produces byte-identical output — the
// property sim/core/spellconst/gen's regeneration test checks.
func generate(class spellconst.Class, outDir, outFile, pkgName, sourcePath string) ([]byte, error) {
	// Most abilities in this package already declare their own per-rank
	// constants by hand, in the shape sim/mage/frostbolt.go established,
	// before this generator existed for their class. Tasks 11 and 12 move
	// those into this file one ability at a time; until an ability's hand
	// declaration is removed, generating one here too would not compile.
	existing, err := existingTopLevelIdentifiers(outDir, outFile)
	if err != nil {
		return nil, err
	}

	// class.Spells is already in a fixed order (spellconst.Load sorts by
	// spell id before grouping), so this ordering does not depend on Go's
	// randomized map iteration anywhere upstream.
	names := map[string]bool{}
	var order []string
	for _, s := range class.Spells {
		if !names[s.Name] {
			names[s.Name] = true
			order = append(order, s.Name)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by sim/core/spellconst/gen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Class: %s\n// Client build: %s\n// Source: %s\n//\n", class.Slug, class.Build, sourcePath)
	fmt.Fprintf(&b, "// Regenerate with `make spellconst`. A coefficient marked\n")
	fmt.Fprintf(&b, "// \"convention\" was derived from the vanilla cast_time/3.5 and\n")
	fmt.Fprintf(&b, "// duration/15 rules because the client table's column was zero;\n")
	fmt.Fprintf(&b, "// per-spell overrides stay in the ability files. Each rank's arrays\n")
	fmt.Fprintf(&b, "// describe its school-damage effect (falling back to its first effect\n")
	fmt.Fprintf(&b, "// when it has none); sim/core/spellconst.Load exposes every effect for\n")
	fmt.Fprintf(&b, "// ability files that need a different one.\n//\n")
	fmt.Fprintf(&b, "// Every array is indexed by the rank label itself (rank 0 included,\n")
	fmt.Fprintf(&b, "// common for a spell with no numbered progression), not by position:\n")
	fmt.Fprintf(&b, "// a gap in the client's own rank numbers is a zero-valued slot here\n")
	fmt.Fprintf(&b, "// too, not a shift. Where the client lists two ids under the same\n")
	fmt.Fprintf(&b, "// (name, rank) — an old id and a reissue, or a player-cast and a\n")
	fmt.Fprintf(&b, "// free/NPC-cast variant — the higher spell_level wins, ties broken by\n")
	fmt.Fprintf(&b, "// the higher id; the id(s) that lost are named in a comment beside the\n")
	fmt.Fprintf(&b, "// rank they were dropped from.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)
	fmt.Fprintf(&b, "// ConstantsBuild is the client build these numbers came from.\n")
	fmt.Fprintf(&b, "const ConstantsBuild = %q\n\n", class.Build)

	claimed := map[string]string{} // Go identifier -> the spell name that claimed it
	for _, name := range order {
		ident := goIdent(name)
		if ident == "" {
			continue
		}
		if owner, ok := claimed[ident]; ok {
			// Two distinct spell names collapse to the same identifier once
			// punctuation is stripped (e.g. "Fireball" and "Fireball!" are
			// different spells in the client). Rather than guess a
			// disambiguating suffix a caller wouldn't expect, this rank is
			// left out of the generated arrays; spellconst.Load still
			// returns it by id or by its exact name.
			fmt.Fprintf(&b, "// skipped: %q collides with %q as the Go identifier %q; look it up by id via spellconst.Load instead.\n\n", name, owner, ident)
			continue
		}
		if existing[ident+"Ranks"] {
			// This ability already declares its own per-rank constants by
			// hand elsewhere in the package (sim/mage/frostbolt.go's own
			// shape, before this generator existed for this class).
			// Generating it here too would redeclare the same identifiers;
			// the hand-written file stays authoritative until an engine
			// task removes it in favor of this one.
			fmt.Fprintf(&b, "// skipped: %q already has a hand-written %sRanks elsewhere in this package.\n\n", name, ident)
			continue
		}
		claimed[ident] = name

		winners, ranks, dropped := resolveRankWinners(class.Ranks(name))
		if len(ranks) == 0 {
			continue
		}
		maxRank := ranks[len(ranks)-1]

		fmt.Fprintf(&b, "// %s: ranks %s present, from build %s.\n", name, formatRankList(ranks), class.Build)
		fmt.Fprintf(&b, "const %sRanks = %d\n\n", ident, maxRank)

		writeArray(&b, ident, "SpellId", "int32", maxRank, func(r int) string {
			w, ok := winners[r]
			if !ok {
				return "0"
			}
			return fmt.Sprint(w.ID)
		})
		writeArray(&b, ident, "Level", "int", maxRank, func(r int) string {
			w, ok := winners[r]
			if !ok {
				return "0"
			}
			return fmt.Sprint(w.SpellLevel)
		})
		writeArray(&b, ident, "CastTime", "int32", maxRank, func(r int) string {
			w, ok := winners[r]
			if !ok {
				return "0"
			}
			return fmt.Sprint(w.CastTimeMS)
		})
		writeArray(&b, ident, "CooldownMS", "int32", maxRank, func(r int) string {
			w, ok := winners[r]
			if !ok {
				return "0"
			}
			return fmt.Sprint(w.EffectiveCooldownMS())
		})
		writeArray(&b, ident, "ManaCost", "float64", maxRank, func(r int) string {
			w, ok := winners[r]
			if !ok {
				return "0"
			}
			return trimFloat(w.Cost)
		})
		writeArray(&b, ident, "SpellCoeff", "float64", maxRank, func(r int) string {
			w, ok := winners[r]
			if !ok {
				return "0"
			}
			return trimFloat(primaryCoefficient(w))
		})

		fmt.Fprintf(&b, "var %sBaseDamage = [%sRanks + 1][]float64{", ident, ident)
		for r := 0; r <= maxRank; r++ {
			if r > 0 {
				fmt.Fprint(&b, ", ")
			}
			w, ok := winners[r]
			if !ok {
				fmt.Fprint(&b, "{0, 0}")
				continue
			}
			amount := trimFloat(primaryAmount(w))
			fmt.Fprintf(&b, "{%s, %s}", amount, amount)
		}
		fmt.Fprintf(&b, "}\n")

		// A coefficient the table did not supply is called out by name,
		// so a reader of the ability file knows which numbers are derived.
		var derived []string
		for _, r := range ranks {
			if e, ok := primaryEffect(winners[r]); ok && e.CoefficientSource == "convention" {
				derived = append(derived, fmt.Sprintf("rank %d", r))
			}
		}
		if len(derived) > 0 {
			fmt.Fprintf(&b, "// unconfirmed: %s coefficient derived from the vanilla convention (%s)\n",
				name, strings.Join(derived, ", "))
		}

		// Every id that lost the same-(name, rank) tiebreak is named here,
		// never silently dropped: a duplicate is picked by spell_level,
		// then id, but the loser can still be the id a beta log or an APL
		// entry references, and this is where a reader finds out why it is
		// not in the array above.
		for _, r := range ranks {
			losers := dropped[r]
			if len(losers) == 0 {
				continue
			}
			winner := winners[r]
			var losing []string
			for _, l := range losers {
				losing = append(losing, fmt.Sprintf("%d (spell_level %d)", l.ID, l.SpellLevel))
			}
			fmt.Fprintf(&b, "// %s rank %d: kept id %d (spell_level %d); dropped %s\n",
				name, r, winner.ID, winner.SpellLevel, strings.Join(losing, ", "))
		}
		fmt.Fprintf(&b, "\n")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated code for package %s does not parse: %w\n%s", pkgName, err, b.String())
	}
	return src, nil
}

// resolveRankWinners groups a spell name's every rank entry by its rank
// label and picks one winner per rank: the entry with the higher
// spell_level, ties broken by the higher id. It returns the winners
// keyed by rank, the distinct rank labels present in ascending order
// (so a caller does not need to range over the map to get a stable
// order), and every losing entry keyed by the rank it lost at.
//
// This is deterministic in itself — sorted purely by (SpellLevel, ID),
// values that come from the JSON, not from iteration order — so it does
// not depend on spellconst.Load's own ordering to produce the same
// result on every call.
func resolveRankWinners(entries []spellconst.Spell) (winners map[int]spellconst.Spell, ranks []int, dropped map[int][]spellconst.Spell) {
	byRank := map[int][]spellconst.Spell{}
	for _, e := range entries {
		byRank[e.Rank] = append(byRank[e.Rank], e)
	}

	winners = make(map[int]spellconst.Spell, len(byRank))
	dropped = map[int][]spellconst.Spell{}
	for r, group := range byRank {
		ranks = append(ranks, r)
		sort.Slice(group, func(i, j int) bool {
			if group[i].SpellLevel != group[j].SpellLevel {
				return group[i].SpellLevel > group[j].SpellLevel
			}
			return group[i].ID > group[j].ID
		})
		winners[r] = group[0]
		if len(group) > 1 {
			losers := append([]spellconst.Spell(nil), group[1:]...)
			sort.Slice(losers, func(i, j int) bool { return losers[i].ID < losers[j].ID })
			dropped[r] = losers
		}
	}
	sort.Ints(ranks)
	return winners, ranks, dropped
}

// formatRankList renders an ascending, deduplicated rank list as
// "1-7" for a contiguous run, "1, 3, 5" for gaps, or a mix of both
// ("1-3, 6") — purely for the generated file's human-readable comment.
func formatRankList(ranks []int) string {
	if len(ranks) == 0 {
		return ""
	}
	var parts []string
	start := ranks[0]
	prev := ranks[0]
	flush := func(end int) {
		if start == end {
			parts = append(parts, fmt.Sprint(start))
		} else {
			parts = append(parts, fmt.Sprintf("%d-%d", start, end))
		}
	}
	for _, r := range ranks[1:] {
		if r == prev+1 {
			prev = r
			continue
		}
		flush(prev)
		start, prev = r, r
	}
	flush(prev)
	return strings.Join(parts, ", ")
}

// schoolDamageEffect is the client's own effect-type code for a direct
// school-damage effect (Frostbolt's damage effect and Bloodthirst's both
// carry it). A rank with more than one effect almost always has exactly
// one of these — the rest are secondary components (a snare, a proc, a
// rage-generation aura) that are not what a single BaseDamage/SpellCoeff
// pair should describe.
const schoolDamageEffect = 2

// primaryEffect is the effect a rank's per-rank arrays describe: its
// school-damage effect if it has one, otherwise the first effect in the
// client's own order. A rank with no effects (none exist in the warrior
// or mage builds this command has generated against, but a future class
// file is not guaranteed the same) reports false rather than panicking.
//
// This is a best-effort default, not a claim about what every spell
// means: spellconst.Load exposes every effect on every rank, and an
// ability file that needs a different one (Mortal Strike's bonus damage
// is on its second effect, not a school-damage effect at all) reads
// spellconst directly rather than this package's generated arrays.
func primaryEffect(s spellconst.Spell) (spellconst.Effect, bool) {
	if len(s.Effects) == 0 {
		return spellconst.Effect{}, false
	}
	for _, e := range s.Effects {
		if e.Effect == schoolDamageEffect {
			return e, true
		}
	}
	return s.Effects[0], true
}

func primaryAmount(s spellconst.Spell) float64 {
	e, ok := primaryEffect(s)
	if !ok {
		return 0
	}
	return e.Amount
}

func primaryCoefficient(s spellconst.Spell) float64 {
	e, ok := primaryEffect(s)
	if !ok {
		return 0
	}
	return e.ResolvedSPCoefficient
}

// existingTopLevelIdentifiers collects every top-level const, var, type
// and func name already declared in dir's .go files, other than
// skipFile itself (the generated file this run is about to overwrite).
// A directory that does not exist yet (a class with no package at all)
// is not an error: it has nothing to collide with.
func existingTopLevelIdentifiers(dir, skipFile string) (map[string]bool, error) {
	idents := map[string]bool{}
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return idents, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", dir, err)
	}
	fset := token.NewFileSet()
	for _, entry := range entries {
		if entry.IsDir() || entry.Name() == skipFile || filepath.Ext(entry.Name()) != ".go" {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, entry.Name()), nil, 0)
		if err != nil {
			return nil, fmt.Errorf("parsing %s: %w", entry.Name(), err)
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.ValueSpec:
						for _, name := range s.Names {
							idents[name.Name] = true
						}
					case *ast.TypeSpec:
						idents[s.Name.Name] = true
					}
				}
			case *ast.FuncDecl:
				if d.Recv == nil {
					idents[d.Name.Name] = true
				}
			}
		}
	}
	return idents, nil
}

// writeArray emits `var <ident><field> = [<ident>Ranks + 1]<typ>{a, b, ...}`,
// one element per rank label from 0 to maxRank inclusive — index r is
// rank r's own data, not the r'th rank that happens to exist. at(r)
// is responsible for returning "0" (or the type's zero literal) for a
// rank label the spell does not have, so a gap reads as "no such rank"
// exactly the same way a rank past the end of a shorter spell's
// progression always has.
func writeArray(b *bytes.Buffer, ident, field, typ string, maxRank int, at func(r int) string) {
	fmt.Fprintf(b, "var %s%s = [%sRanks + 1]%s{", ident, field, ident, typ)
	for r := 0; r <= maxRank; r++ {
		if r > 0 {
			fmt.Fprint(b, ", ")
		}
		fmt.Fprint(b, at(r))
	}
	fmt.Fprintf(b, "}\n")
}

func trimFloat(f float64) string {
	return strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.4f", f), "0"), ".")
}

// goIdent turns "Mortal Strike" into "MortalStrike". Leading/trailing
// whitespace in the client's own spell name (a handful of warrior spells
// carry it, e.g. a stray leading space on one "Increased Spell Hit
// Chance") is trimmed by spellconst.Load before this ever sees the name,
// so two spells that differ only by that whitespace still collide into
// one identifier deliberately, not by accident.
//
// A set-bonus tooltip's name can start with a version string and carry
// punctuation Go identifiers do not allow, e.g. "1.60.0 - Item - Tier 1
// - Warrior - Arms/Fury 2P Bonus - Haste": every rune that is not a
// letter or digit is treated as a separator, and an identifier that
// still starts with a digit gets an "X" prefix, since Go identifiers
// never may.
func goIdent(name string) string {
	var out strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	}) {
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}
	ident := out.String()
	if ident != "" && unicode.IsDigit(rune(ident[0])) {
		ident = "X" + ident
	}
	return ident
}
