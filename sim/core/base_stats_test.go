// Pins the H3 ruling from the Task 4 fix round: research/08-stats.md §7
// leaves the baseline Agility/Intellect-to-Crit conversion "entirely
// unpublished" for the unified model, so every class keeps its pre-merge
// sources — a hybrid that converted both keeps both (stacking, marked
// unconfirmed); a class that converted only one keeps only that one,
// unchanged. All nine classes that wire a base-stat-to-Crit dependency are
// asserted here against the one table (sim/core/base_stats.go), which is
// the single place a later ruling edits instead of the nine
// AddStatDependency call sites across sim/druid, sim/shaman,
// sim/paladin, sim/warlock, sim/hunter, sim/rogue, sim/mage, sim/priest
// and sim/warrior.
func TestCritStatSourcesArePinned(t *testing.T) {
	expected := map[proto.Class]CritStatSources{
		// Hybrids: stack Agility- and Intellect-derived Crit, unconfirmed.
		proto.Class_ClassDruid:   {Agility: true, Intellect: true},
		proto.Class_ClassShaman:  {Agility: true, Intellect: true},
		proto.Class_ClassPaladin: {Agility: true, Intellect: true},
		proto.Class_ClassWarlock: {Agility: true, Intellect: true},
		proto.Class_ClassHunter:  {Agility: true, Intellect: true},
		// Single-source: unchanged from before the merge.
		proto.Class_ClassRogue:   {Agility: true},
		proto.Class_ClassWarrior: {Agility: true},
		proto.Class_ClassMage:    {Intellect: true},
		proto.Class_ClassPriest:  {Intellect: true},
	}

	if len(ClassCritStatSources) != len(expected) {
		t.Fatalf("ClassCritStatSources has %d entries, want %d — a class was added or removed without updating this pin",
			len(ClassCritStatSources), len(expected))
	}
	for class, want := range expected {
		got, ok := ClassCritStatSources[class]
		if !ok {
			t.Errorf("ClassCritStatSources is missing %v", class)
			continue
		}
		if got != want {
			t.Errorf("ClassCritStatSources[%v] = %+v, want %+v", class, got, want)
		}
	}
}

// Demonstrates (and pins) the actual arithmetic: a hybrid class's Agility
// and Intellect both add into the one Crit stat, because
// StatDependencyManager sums every enabled dependency into its
// destination (see TestMultipleStatDep in sim/core/stats/deps_test.go for
// the same behaviour at the mechanism level). If a later ruling on
// research/08-stats.md §7 decides a hybrid should draw from only one
// source, this is the test that must change, alongside
// ClassCritStatSources.
func TestCritStatSourcesStackForHybrids(t *testing.T) {
	class := proto.Class_ClassDruid
	agi, intel := 100.0, 200.0

	character := &Character{}
	AddCritStatDependencies(character, class)

	result := character.SortAndApplyStatDependencies(stats.Stats{
		stats.Agility:   agi,
		stats.Intellect: intel,
	})

	wantCrit := agi*CritPerAgiAtLevel[class]*CritRatingPerCritChance + intel*CritPerIntAtLevel[class]*CritRatingPerCritChance
	if result[stats.Crit] != wantCrit {
		t.Fatalf("Crit = %v, want %v (Agility and Intellect contributions summed)", result[stats.Crit], wantCrit)
	}
}

// A class absent from ClassCritStatSources (every class that wires a
// base-stat-to-Crit dependency is listed — see TestCritStatSourcesArePinned)
// gets neither dependency, and the helper must not panic on an unlisted
// class.
func TestCritStatSourcesNoOpForUnlistedClass(t *testing.T) {
	character := &Character{}
	AddCritStatDependencies(character, proto.Class_ClassUnknown)

	result := character.SortAndApplyStatDependencies(stats.Stats{
		stats.Agility:   100,
		stats.Intellect: 100,
	})
	if result[stats.Crit] != 0 {
		t.Fatalf("Crit = %v, want 0 for a class with no CritStatSources entry", result[stats.Crit])
	}
}

// A single-source class (e.g. Rogue: Agility only) draws Crit from only
// that stat — the Intellect it also has does not leak in, unlike a
// hybrid's deliberate stacking in TestCritStatSourcesStackForHybrids.
func TestCritStatSourcesSingleSourceDoesNotStack(t *testing.T) {
	class := proto.Class_ClassRogue
	agi, intel := 100.0, 200.0

	character := &Character{}
	AddCritStatDependencies(character, class)

	result := character.SortAndApplyStatDependencies(stats.Stats{
		stats.Agility:   agi,
		stats.Intellect: intel,
	})

	wantCrit := agi * CritPerAgiAtLevel[class] * CritRatingPerCritChance
	if result[stats.Crit] != wantCrit {
		t.Fatalf("Crit = %v, want %v (Agility only; Intellect must not contribute)", result[stats.Crit], wantCrit)
	}
}

// Every rating constant must come from the client tables, not from a
// literal somebody typed. The generated file names the build it came
// from, and the test refuses a file that has been hand-edited.
func TestBaseStatsFileIsGenerated(t *testing.T) {
	b, err := os.ReadFile("base_stats_auto_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	src := string(b)
	if !strings.Contains(src, "Code generated by tools/base_stats_parser.py. DO NOT EDIT.") {
		t.Error("base_stats_auto_gen.go is missing the generated-code header")
	}
	if strings.Contains(src, "TODO") {
		t.Error("base_stats_auto_gen.go contains a TODO; it is generated, so a TODO means it was hand-edited")
	}
	if BaseStatsBuild == "" {
		t.Error("BaseStatsBuild is empty; the generator must record the client build")
	}
	// Every constant carries a note saying which build its value actually
	// came from, so the file is readable line by line rather than being
	// labelled wholly one thing or another.
	if BaseStatsBuild != "" && !strings.Contains(src, "// source build:") {
		t.Error("base_stats_auto_gen.go carries no per-constant source-build notes")
	}
}

// Ratings are straight percentages in the Classic lineage and Forever
// keeps that (research/08-stats.md 2 and 12.4), so each of these is
// exactly 1: one point of rating is one percent. A regeneration that
// produced anything else - a later-expansion conversion factor, say -
// would silently scale every hit and crit chance in the engine, so the
// exact value is asserted rather than its sign.
func TestRatingConstantsAreOneToOnePercentages(t *testing.T) {
	cases := []struct {
		name string
		got  float64
	}{
		{"CritRatingPerCritChance", CritRatingPerCritChance},
		{"HitRatingPerHitChance", HitRatingPerHitChance},
		{"HasteRatingPerHastePercent", HasteRatingPerHastePercent},
		{"ExpertiseRatingPerExpertiseChance", ExpertiseRatingPerExpertiseChance},
	}
	for _, c := range cases {
		if c.got != 1 {
			t.Errorf("%s = %v, want exactly 1 (Forever uses flat percentages)", c.name, c.got)
		}
	}
}

// The four defensive conversions are read from combatratings.txt for
// build 1.60.1.69893, so the test pins them against that table rather
// than against a literal: a regeneration that silently zeroed one would
// otherwise pass.
//
// DefenseRatingPerDefense is allowed to equal 1: the pinned 1.60.1.69893
// combatratings.txt table carries "Defense Skill" as a flat 1 across
// every level (verified directly against the vendored file), unlike
// Dodge/Parry/Block, which are not 1. That is a real measured value for
// this constant, not the flat-percentage sentinel the other three are
// checked against.
func TestDefensiveConversionsComeFromTheTable(t *testing.T) {
	cases := []struct {
		name        string
		got         float64
		canEqualOne bool
	}{
		{"DefenseRatingPerDefense", DefenseRatingPerDefense, true},
		{"DodgeRatingPerDodgeChance", DodgeRatingPerDodgeChance, false},
		{"ParryRatingPerParryChance", ParryRatingPerParryChance, false},
		{"BlockRatingPerBlockChance", BlockRatingPerBlockChance, false},
	}
	for _, c := range cases {
		if c.got <= 0 {
			t.Errorf("%s = %v; a conversion read from combatratings.txt is positive", c.name, c.got)
		}
		if c.got == 1 && !c.canEqualOne {
			t.Errorf("%s = 1; that is the flat-percentage value, which means the generator did not read the table for it", c.name)
		}
	}
}

// Expertise is already modelled in the attack table (spell_outcome.go
// reduces dodge and parry by stats.Expertise/100) and is dormant in
// vanilla but live for Forever.
func TestExpertiseIsAFlatPercentage(t *testing.T) {
	// The item unit is a percentage (Edgemaster's is 1.0%), not
	// expertise points, so the conversion is 1:1 and the quarter-percent
	// quantisation from later expansions must not come back.
	if ExpertiseRatingPerExpertiseChance != 1 {
		t.Errorf("ExpertiseRatingPerExpertiseChance = %v, want 1", ExpertiseRatingPerExpertiseChance)
	}
	b, err := os.ReadFile("base_stats_auto_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(b), "ExpertisePerQuarterPercentReduction") {
		t.Error("the quarter-percent expertise quantisation is back; Forever's item unit is a percentage")
	}
	if strings.Contains(string(b), "Resilience") {
		t.Error("a resilience constant is back; Forever adds no resilience")
	}
}

// Until the per-race/class base-stat table is mined for Forever, every
// name here still carries an unconfirmed value. The engine says so out
// loud, and the spec support page repeats it, rather than letting a
// player assume the numbers are Forever's.
func TestProvisionalConstantsAreDeclared(t *testing.T) {
	got := ProvisionalConstants()
	if len(got) == 0 {
		t.Skip("no provisional constants: the Forever tables have landed, and this test has done its job")
	}
	for _, name := range got {
		if name == "" {
			t.Error("ProvisionalConstants() contains an empty name")
		}
	}
	b, err := os.ReadFile("base_stats_provisional.go")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(b), "unconfirmed") {
		t.Error("base_stats_provisional.go must mark its values unconfirmed")
	}
}

// Skyborne base stats are not in any mined table. They ship as clones of
// a vanilla row, marked, and named by ProvisionalConstants, so nobody
// mistakes a Skyborne sim's numbers for measured ones. When the real
// table lands this test fails, which is the point.
func TestSkyborneBaseStatsAreDeclaredClones(t *testing.T) {
	al := BaseStats[BaseStatsKey{Race: proto.Race_RaceHighOrderSkyborne, Class: proto.Class_ClassWarrior, Level: 60}]
	human := BaseStats[BaseStatsKey{Race: proto.Race_RaceHuman, Class: proto.Class_ClassWarrior, Level: 60}]
	if al != human {
		t.Log("Skyborne base stats are no longer a clone of Human: a real table has landed. Remove the clone, remove this test, and drop the two entries from ProvisionalConstants.")
		t.Fail()
	}
	var named int
	for _, n := range ProvisionalConstants() {
		if strings.Contains(n, "Skyborne") {
			named++
		}
	}
	if named != 2 {
		t.Errorf("ProvisionalConstants names %d Skyborne entries, want 2", named)
	}
}
