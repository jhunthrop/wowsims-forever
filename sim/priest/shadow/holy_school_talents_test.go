// Searing Light 14909 (client 1.60.1.70707) effect 0 is aura 79
// (SPELL_AURA_MOD_DAMAGE_PERCENT_DONE) on school mask 2, Holy: "Increases
// your Holy damage done by 5%" at 2/2. It is every Holy damage the priest
// deals (Smite, Holy Fire, Penance and Holy Nova's damage), multiplied like
// Darkness's aura 79 on Shadow, not an additive share of two named spells.
func TestSearingLightIsAllHolyDamageDone(t *testing.T) {
	_, without := buildShadowPriestForTest(t, priestTalentStringWithRank(t, "searing_light", 0))
	_, with := buildShadowPriestForTest(t, priestTalentStringWithRank(t, "searing_light", 2))

	got := with.PseudoStats.SchoolDamageDealtMultiplier[stats.SchoolIndexHoly] /
		without.PseudoStats.SchoolDamageDealtMultiplier[stats.SchoolIndexHoly]
	if math.Abs(got-1.05) > 1e-9 {
		t.Errorf("Searing Light 2/2 Holy damage done = x%v, want x1.05", got)
	}
	for _, spells := range [][]*core.Spell{with.Smite, with.HolyFire} {
		for _, spell := range spells {
			if spell != nil && spell.DamageMultiplierAdditive != 1 {
				t.Errorf("%v carries additive damage %v; Searing Light is a school multiplier", spell.ActionID, spell.DamageMultiplierAdditive)
			}
		}
	}
}

// Silent Resolve 14523 effect 0 is aura 10 (MOD_THREAT) on school mask 34,
// Holy and Shadow: "Reduces the threat generated by your spells by 30%".
func TestSilentResolveCoversShadowThreat(t *testing.T) {
	_, built := buildShadowPriestForTest(t, priestTalentStringWithRank(t, "silent_resolve", 3))
	for _, spell := range built.MindBlast {
		if spell == nil {
			continue
		}
		if math.Abs(spell.ThreatMultiplier-0.70) > 1e-9 {
			t.Errorf("Mind Blast threat multiplier = %v with Silent Resolve 3/3, want 0.70", spell.ThreatMultiplier)
		}
	}
}
