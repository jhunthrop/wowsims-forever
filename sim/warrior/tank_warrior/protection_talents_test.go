const (
	defensiveStanceThreat = 1.3 // client spell 7376: +30%
	defiancePerRank       = 0.05
	floatEpsilon          = 1e-9
)

func assertNear(t *testing.T, label string, got, want float64) {
	t.Helper()
	if math.Abs(got-want) > floatEpsilon {
		t.Errorf("%s = %v, want %v", label, got, want)
	}
}

// attackTaken delivers one attack with the outcome to the tank, as the
// boss's swing would.
func attackTaken(sim *core.Simulation, war *warrior.Warrior, outcome core.HitOutcome) {
	boss := sim.Encounter.TargetUnits[0]
	swing := boss.AutoAttacks.MHAuto()
	result := swing.NewResult(&war.Unit)
	result.Outcome = outcome
	war.OnSpellHitTaken(sim, swing, result)
	swing.DisposeResult(result)
}

// Defiance: "Increases all threat generated in Defensive stance by an
// additional 5%/10%/15% while a shield is equipped", added to the stance's
// own 30%.
func TestDefianceAddsToTheStanceThreatWithAShield(t *testing.T) {
	for rank := 0; rank <= 3; rank++ {
		talents := talentsWith(t, emptyTalents, "defiance", rank)

		withShield, _ := buildTank(t, talents, true)
		assertNear(t, "threat with a shield", withShield.PseudoStats.ThreatMultiplier, defensiveStanceThreat+defiancePerRank*float64(rank))

		withoutShield, _ := buildTank(t, talents, false)
		assertNear(t, "threat without a shield", withoutShield.PseudoStats.ThreatMultiplier, defensiveStanceThreat)
	}
}

// Master of Defense: "a 50%/100% chance to generate 5 Rage when you Dodge or
// Parry while a shield is equipped".
func TestMasterOfDefenseGrantsRageOnDodgeAndParry(t *testing.T) {
	for _, outcome := range []core.HitOutcome{core.OutcomeDodge, core.OutcomeParry} {
		war, sim := buildTank(t, talentsWith(t, emptyTalents, "master_of_defense", 2), true)
		before := war.CurrentRage()
		attackTaken(sim, war, outcome)
		assertNear(t, "rage gained at rank 2", war.CurrentRage()-before, 5)
	}

	war, sim := buildTank(t, talentsWith(t, emptyTalents, "master_of_defense", 2), true)
	before := war.CurrentRage()
	attackTaken(sim, war, core.OutcomeHit)
	if war.CurrentRage() != before {
		t.Errorf("a landed hit gave %v rage, want none", war.CurrentRage()-before)
	}

	war, sim = buildTank(t, talentsWith(t, emptyTalents, "master_of_defense", 2), false)
	before = war.CurrentRage()
	attackTaken(sim, war, core.OutcomeDodge)
	if war.CurrentRage() != before {
		t.Errorf("a dodge without a shield gave %v rage, want none", war.CurrentRage()-before)
	}
}

func TestMasterOfDefenseRankOneProcsAboutHalfTheTime(t *testing.T) {
	war, sim := buildTank(t, talentsWith(t, emptyTalents, "master_of_defense", 1), true)
	const attempts = 4000
	procs := 0
	for i := 0; i < attempts; i++ {
		before := war.CurrentRage()
		attackTaken(sim, war, core.OutcomeParry)
		if war.CurrentRage() > before {
			procs++
		}
		war.SpendRage(sim, war.CurrentRage(), war.RageRefundMetrics)
	}
	if share := float64(procs) / attempts; share < 0.46 || share > 0.54 {
		t.Errorf("rank 1 proc share = %v, want about 0.5", share)
	}
}

