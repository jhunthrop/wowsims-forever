// Improved Shield Wall: "Reduces the cooldown of your Shield Wall ability by
// 5.5 min" / "by 11.0 min", off the client's 15 minutes.
func TestImprovedShieldWallCutsTheCooldown(t *testing.T) {
	for rank, want := range map[int]time.Duration{0: 15 * time.Minute, 1: 9*time.Minute + 30*time.Second, 2: 4 * time.Minute} {
		war, _ := buildTank(t, talentsWith(t, emptyTalents, "improved_shield_wall", rank), true)
		wall := war.GetSpell(core.ActionID{SpellID: warrior.ShieldWallSpellId[0]})
		if wall == nil {
			t.Fatal("Shield Wall is not registered")
		}
		if got := wall.CD.Duration; got != want {
			t.Errorf("rank %d: cooldown %v, want %v", rank, got, want)
		}
	}
}

// Shield Wall: -60% damage taken for 12 seconds.
func TestShieldWallCutsDamageTakenBySixtyPercentFor12Seconds(t *testing.T) {
	war, sim := buildTank(t, emptyTalents, true)
	before := war.PseudoStats.DamageTakenMultiplier
	wall := war.GetSpell(core.ActionID{SpellID: warrior.ShieldWallSpellId[0]})
	wall.ApplyEffects(sim, &war.Unit, wall)

	assertNear(t, "damage taken multiplier", war.PseudoStats.DamageTakenMultiplier, before*0.4)
	aura := war.GetAura("Shield Wall")
	if aura == nil || !aura.IsActive() || aura.Duration != 12*time.Second {
		t.Fatalf("Shield Wall aura = %+v, want active for 12s", aura)
	}
	aura.Deactivate(sim)
	assertNear(t, "damage taken multiplier after it ends", war.PseudoStats.DamageTakenMultiplier, before)
}

// Shield Block: +75% block for 7 seconds and two charges, a block spending
// one.
func TestShieldBlockHasTwoChargesAndSevenSeconds(t *testing.T) {
	war, sim := buildTank(t, emptyTalents, true)
	if war.ShieldBlockAura.Duration != 7*time.Second {
		t.Errorf("duration = %v, want 7s", war.ShieldBlockAura.Duration)
	}
	war.ShieldBlock.ApplyEffects(sim, &war.Unit, war.ShieldBlock.Spell)
	if got := war.ShieldBlockAura.GetStacks(); got != 2 {
		t.Fatalf("charges after the cast = %d, want 2", got)
	}

	attackTaken(sim, war, core.OutcomeBlock)
	if got := war.ShieldBlockAura.GetStacks(); got != 1 {
		t.Errorf("charges after one block = %d, want 1", got)
	}
	war.ShieldBlock.ApplyEffects(sim, &war.Unit, war.ShieldBlock.Spell)
	if got := war.ShieldBlockAura.GetStacks(); got != 2 {
		t.Errorf("a recast restores the charges: %d, want 2", got)
	}
	attackTaken(sim, war, core.OutcomeBlock)
	attackTaken(sim, war, core.OutcomeBlock)
	if war.ShieldBlockAura.IsActive() {
		t.Error("the aura outlives its second block")
	}
}

// Last Stand: 30% of maximum health for 20 seconds, then it is lost.
func TestLastStandGrantsAndThenLosesThirtyPercentOfHealth(t *testing.T) {
	war, sim := buildTank(t, talentsWith(t, emptyTalents, "last_stand", 1), true)
	base := war.MaxHealth()
	lastStand := war.GetSpell(core.ActionID{SpellID: warrior.LastStandSpellId[0]})
	lastStand.ApplyEffects(sim, &war.Unit, lastStand)

	assertNear(t, "maximum health", war.MaxHealth(), base*1.3)
	assertNear(t, "current health", war.CurrentHealth(), base*1.3)
	war.GetAura("Last Stand").Deactivate(sim)
	assertNear(t, "maximum health after it ends", war.MaxHealth(), base)
	assertNear(t, "current health after it ends", war.CurrentHealth(), base)
}

// Revenge is cast only after the tank dodges, parries or blocks, at the top
// trainer rank, for the client's 5 rage less Focused Rage.
func TestRevengeNeedsADefensiveOutcomeAndCostsFiveRage(t *testing.T) {
	war, sim := buildTank(t, emptyTalents, true)
	war.SpendRage(sim, war.CurrentRage(), war.RageRefundMetrics)
	war.AddRage(sim, 50, war.RageRefundMetrics)
	if war.Revenge.CanCast(sim, sim.Encounter.TargetUnits[0]) {
		t.Fatal("Revenge is castable before any defensive outcome")
	}
	if war.Revenge.ActionID.SpellID != warrior.RevengeSpellId[warrior.RevengeRanks-1] {
		t.Errorf("Revenge id = %d, want the top trainer rank %d", war.Revenge.ActionID.SpellID, warrior.RevengeSpellId[warrior.RevengeRanks-1])
	}
	for _, outcome := range []core.HitOutcome{core.OutcomeDodge, core.OutcomeParry, core.OutcomeBlock} {
		fresh, freshSim := buildTank(t, emptyTalents, true)
		fresh.AddRage(freshSim, 50, fresh.RageRefundMetrics)
		attackTaken(freshSim, fresh, outcome)
		if !fresh.Revenge.CanCast(freshSim, freshSim.Encounter.TargetUnits[0]) {
			t.Errorf("Revenge is not castable after %v", outcome)
		}
	}
	assertNear(t, "Revenge cost", war.Revenge.Cost.GetCurrentCost(), 5)
}

// Thunder Clap works from Defensive Stance, with the learnable family's 6 s
// cooldown and 20% slow.
func TestThunderClapIsCastableInDefensiveStance(t *testing.T) {
	war, sim := buildTank(t, emptyTalents, true)
	if !war.ThunderClap.StanceMask.Matches(warrior.DefensiveStance) {
		t.Fatal("Thunder Clap is not a Defensive Stance spell")
	}
	war.AddRage(sim, 50, war.RageRefundMetrics)
	if !war.ThunderClap.CanCast(sim, sim.Encounter.TargetUnits[0]) {
		t.Error("Thunder Clap cannot be cast in Defensive Stance")
	}
	if got := war.ThunderClap.CD.Duration; got != 6*time.Second {
		t.Errorf("cooldown = %v, want 6s", got)
	}
	if got := war.ThunderClap.RelatedSelfBuff.Duration; got != 30*time.Second {
		t.Errorf("the slow lasts %v at rank 6, want 30s", got)
	}
}

