#!/usr/bin/env python3
"""Generate sim/core/spell_max_level_auto_gen.go: the client MaxLevel of
every spell whose MaxLevel is not its SpellLevel + 5.

Forever's low-rank penalty (core.SpellLevelPenalty) runs from a rank's
SpellLevels.MaxLevel: the rank keeps its whole spell power coefficient until
the caster is 12 levels past MaxLevel, then loses 5% a level. Nearly every
trained heal rank has MaxLevel = SpellLevel + 5, so the rule reads as "17
levels past the learn level"; the ranks that do not are the ones the beta
measurements caught running early or late (Lesser Heal rank 1, MaxLevel 3;
Healing Touch and Holy Light rank 1, MaxLevel 5). The engine keys a spell
with no row here on its learn level (RequiredLevel + 5), so this set holds
only the exceptions: MaxLevel above zero and not SpellLevel + 5.

    SpellLevels.csv  DifficultyID, MaxLevel, SpellLevel, SpellID
    SpellName.csv    Name_lang (the comment beside each id)

Usage (from the fork root):
    python3 -I tools/spellmaxlevel/gen.py <site repo>/data/builds/<build> [--check]

Run it with `python3 -I` from a directory that holds no other python files.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

MAX_LEVEL_AFTER_SPELL_LEVEL = 5
FORK_ROOT = Path(__file__).resolve().parent.parent.parent
OUT = FORK_ROOT / "sim" / "core" / "spell_max_level_auto_gen.go"


def read_csv(raw: Path, name: str) -> list[dict[str, str]]:
    with open(raw / name, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def exceptions(raw: Path) -> list[tuple[int, int, str]]:
    names = {int(r["ID"]): r["Name_lang"] for r in read_csv(raw, "SpellName.csv")}
    found: dict[int, int] = {}
    for row in read_csv(raw, "SpellLevels.csv"):
        if row.get("DifficultyID", "0") not in ("0", ""):
            continue
        max_level, spell_level = int(row["MaxLevel"]), int(row["SpellLevel"])
        if max_level > 0 and max_level != spell_level + MAX_LEVEL_AFTER_SPELL_LEVEL:
            found[int(row["SpellID"])] = max_level
    return [(spell_id, found[spell_id], names.get(spell_id, "")) for spell_id in sorted(found)]


def render(build: str, rows: list[tuple[int, int, str]]) -> str:
    body = "".join(f"\t{spell_id}: {max_level}, // {name}\n" for spell_id, max_level, name in rows)
    return (
        "// Code generated by tools/spellmaxlevel/gen.py. DO NOT EDIT.\n"
        "//\n"
        f"// Client build: {build}\n"
        "//\n"
        "// SpellLevels.MaxLevel of every spell whose MaxLevel is set and is not\n"
        "// its SpellLevel + 5 (the low-rank penalty's key, SpellLevelPenalty).\n"
        "// Regenerate with `make spellmaxlevel`.\n\n"
        "package core\n\n"
        "var clientSpellMaxLevel = map[int32]int{\n"
        f"{body}"
        "}\n"
    )


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    build_dir = Path(args[0]).resolve()
    text = render(build_dir.name, exceptions(build_dir / "raw"))
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
