#!/usr/bin/env python3
"""Generate sim/core/periodic_crit_auto_gen.go: every spell whose periodic
damage the Forever client lets crit.

Forever's periodic damage can crit, spell by spell. The client says which
spells with SpellMisc Attributes_8 bit 0x200 (SPELL_ATTR8_PERIODIC_CAN_CRIT):
Corruption, Shadow Word: Pain, Immolate, Moonfire, Serpent Sting, Rend and
the other trained damage-over-time spells carry it; the ground-targeted
channels (Blizzard, Rain of Fire, Hurricane) and server-only tick spells
(Ignite, Deep Wounds) do not. The engine reads the set in core.newDot, so a
dot crits exactly when the client says it can.

    SpellMisc.csv    Attributes_8, SpellID
    SpellEffect.csv  EffectAura (3 periodic damage, 53 periodic leech,
                     89 periodic damage percent)
    SpellName.csv    Name_lang (the comment beside each id)

Usage (from the fork root):
    python3 -I tools/periodiccrit/gen.py <site repo>/data/builds/<build> [--check]

Run it with `python3 -I` from a directory that holds no other python files.
"""
from __future__ import annotations

import collections
import csv
import sys
from pathlib import Path

PERIODIC_CAN_CRIT = 0x200
PERIODIC_DAMAGE_AURAS = {"3", "53", "89"}
FORK_ROOT = Path(__file__).resolve().parent.parent.parent
OUT = FORK_ROOT / "sim" / "core" / "periodic_crit_auto_gen.go"


def read_csv(raw: Path, name: str) -> list[dict[str, str]]:
    with open(raw / name, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def base_difficulty(row: dict[str, str]) -> bool:
    return row.get("DifficultyID", "0") in ("0", "")


def periodic_crit_spells(raw: Path) -> list[tuple[int, str]]:
    auras: dict[int, set[str]] = collections.defaultdict(set)
    for row in read_csv(raw, "SpellEffect.csv"):
        if base_difficulty(row):
            auras[int(row["SpellID"])].add(row["EffectAura"])
    names = {int(r["ID"]): r["Name_lang"] for r in read_csv(raw, "SpellName.csv")}
    found = set()
    for row in read_csv(raw, "SpellMisc.csv"):
        spell_id = int(row["SpellID"])
        if not base_difficulty(row) or not int(row["Attributes_8"]) & PERIODIC_CAN_CRIT:
            continue
        if auras.get(spell_id, set()) & PERIODIC_DAMAGE_AURAS:
            found.add(spell_id)
    return [(spell_id, names.get(spell_id, "")) for spell_id in sorted(found)]


def render(build: str, spells: list[tuple[int, str]]) -> str:
    rows = "".join(f"\t{spell_id}: {{}}, // {name}\n" for spell_id, name in spells)
    return (
        "// Code generated by tools/periodiccrit/gen.py. DO NOT EDIT.\n"
        "//\n"
        f"// Client build: {build}\n"
        "//\n"
        "// Every spell with a periodic damage effect whose SpellMisc Attributes_8\n"
        "// carries 0x200 (SPELL_ATTR8_PERIODIC_CAN_CRIT): its ticks can crit.\n"
        "// Regenerate with `make periodiccrit`.\n\n"
        "package core\n\n"
        "var clientPeriodicCanCrit = map[int32]struct{}{\n"
        f"{rows}"
        "}\n"
    )


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    build_dir = Path(args[0]).resolve()
    text = render(build_dir.name, periodic_crit_spells(build_dir / "raw"))
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
