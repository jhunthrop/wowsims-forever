func warriorClass(t *testing.T) talents.Class {
	t.Helper()
	return fixtureClass(t, "warrior")
}

// fixtureClass reads one class from testdata. Every class the generator
// writes has a fixture, so the regeneration test below needs no site
// checkout and no network.
func fixtureClass(t *testing.T, slug string) talents.Class {
	t.Helper()
	c, err := talents.Load(filepath.Join("testdata", slug+".json"))
	if err != nil {
		t.Fatal(err)
	}
	if c.Slug != slug {
		t.Fatalf("testdata/%s.json declares class_slug %q", slug, c.Slug)
	}
	return c
}

func mustGoFile(t *testing.T, c talents.Class) string {
	t.Helper()
	s, err := goFile(c)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func mustUITreeJSON(t *testing.T, c talents.Class) string {
	t.Helper()
	s, err := uiTreeJSON(c)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

// The proto message's field order IS the talent string's order, because
// core.FillTalentsProto walks the fields positionally. So the emitted
// message must be the three trees concatenated in position order, each
// tier-then-column, with field numbers 1..N in that order and no gaps.
func TestProtoMessageIsInTalentStringOrder(t *testing.T) {
	c := warriorClass(t)
	got := protoMessage(c)
	lines := []string{}
	for _, l := range strings.Split(got, "\n") {
		l = strings.TrimSpace(l)
		if strings.HasSuffix(l, ";") && !strings.HasPrefix(l, "//") {
			lines = append(lines, l)
		}
	}
	var want int
	for _, tr := range c.Trees {
		want += len(tr.Talents)
	}
	if len(lines) != want {
		t.Fatalf("the message has %d fields, want %d", len(lines), want)
	}
	if !strings.Contains(got, "message WarriorTalents {") {
		t.Errorf("the message is not named WarriorTalents:\n%s", got[:200])
	}
	// First field is Arms tier 0 column 0, last is Protection's last.
	first := c.Trees[0].Talents[0]
	if !strings.Contains(lines[0], c.FieldName(first)+" = 1;") {
		t.Errorf("field 1 is %q, want %q", lines[0], c.FieldName(first))
	}
	last := c.Trees[2].Talents[len(c.Trees[2].Talents)-1]
	if !strings.Contains(lines[len(lines)-1], c.FieldName(last)) {
		t.Errorf("the last field is %q, want %q", lines[len(lines)-1], c.FieldName(last))
	}
}

// A one-rank talent is a bool and a multi-rank talent is an int32, which
// is the convention the nine hand-written messages already use, so
// nothing downstream has to change.
func TestOneRankTalentsAreBools(t *testing.T) {
	c := warriorClass(t)
	got := protoMessage(c)
	for _, tr := range c.Trees {
		for _, ta := range tr.Talents {
			field := c.FieldName(ta)
			wantType := "int32"
			if ta.MaxRank == 1 {
				wantType = "bool"
			}
			if !strings.Contains(got, wantType+" "+field+" =") {
				t.Errorf("%s (max rank %d) is not declared as %s", field, ta.MaxRank, wantType)
			}
		}
	}
}

// The generated Go file carries the sizes, the build, and the two lookup
// maps the spec tasks read instead of typing spell ids.
func TestGoFileCarriesSizesBuildAndIDs(t *testing.T) {
	c := warriorClass(t)
	got := mustGoFile(t, c)
	for _, want := range []string{
		"// Code generated by tools/talentgen. DO NOT EDIT.",
		"package warrior",
		"var TalentTreeSizes = [3]int{17, 18, 18}",
		`const TalentsBuild = "1.60.1.69893"`,
		"var TalentNodeIDs = map[string]int32{",
		"var TalentSpellIDs = map[string][]int32{",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("the generated Go file does not contain %q", want)
		}
	}
	// The node id itself, matched with the alignment gofmt gives the map
	// rather than a fixed single space, so a longer field name in a later
	// build does not fail this for a reason that is not a defect.
	for _, want := range []*regexp.Regexp{
		regexp.MustCompile(`"improved_heroic_strike":\s+105958,`),
		regexp.MustCompile(`"improved_heroic_strike":\s+\{12282, 12282, 12282\},`),
	} {
		if !want.MatchString(got) {
			t.Errorf("the generated Go file has no entry matching %s", want)
		}
	}
}

// The UI tree JSON the engine's own talent picker reads must have one
// entry per talent with its grid position, so the fork stays buildable.
// Its fieldName is the LOWER-CAMEL spelling, because the picker indexes
// the generated TypeScript proto object with it and protoc-gen-ts
// camel-cases every field; a snake_case name there type-checks (the
// picker's field is `keyof TalentsProto | string`) and then reads
// undefined for every talent, which is the silent wrongness this whole
// task exists to remove.
func TestUITreeJSONHasEveryTalent(t *testing.T) {
	c := warriorClass(t)
	got := mustUITreeJSON(t, c)
	for _, tr := range c.Trees {
		if !strings.Contains(got, `"name": "`+tr.Name+`"`) {
			t.Errorf("the UI JSON is missing the %s tree", tr.Name)
		}
		for _, ta := range tr.Talents {
			if !strings.Contains(got, `"fieldName": "`+uiFieldName(c.FieldName(ta))+`"`) {
				t.Errorf("the UI JSON is missing %q", ta.Name)
			}
		}
	}
}

// The camel-casing is derived from the proto field name, so the two
// cannot drift: one talent, one name, spelled for each side.
func TestUIFieldNameIsTheProtoFieldCamelCased(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"improved_heroic_strike", "improvedHeroicStrike"},
		{"deflection", "deflection"},
		{"winters_chill", "wintersChill"},
		{"two_handed_weapon_specialization", "twoHandedWeaponSpecialization"},
	} {
		if got := uiFieldName(tc.in); got != tc.want {
			t.Errorf("uiFieldName(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}

// The round trip that actually matters: a talent string built from a
// point spend must READ BACK as the same spend, through the same
// core.FillTalentsProto the engine uses and the same generated message.
// A size that is one out does not error, it reads the wrong talent,
// which is why this goes through the real reader rather than measuring
// the string's length.
//
// FillTalentsProto walks the message by FIELD NUMBER (character.go:746,
// fieldDescriptors.ByNumber(offset+talentIdx+1)), which is exactly the
// order protoMessage emits, so this test is what pins the two together.
func TestTalentStringRoundTripsThroughFillTalentsProto(t *testing.T) {
	c := warriorClass(t)
	sizes := c.TreeSizes()

	// Spend one point in every talent that has a rank to spare, and the
	// max in every one-rank talent, so every field is exercised and no
	// value is the zero that a mis-indexed read would also produce.
	spend := make([][]int, 3)
	want := map[string]int{}
	for i, tree := range c.Trees {
		spend[i] = make([]int, len(tree.Talents))
		for j, ta := range tree.Talents {
			v := 1
			if ta.MaxRank > 2 {
				v = 2
			}
			spend[i][j] = v
			want[c.FieldName(ta)] = v
		}
	}

	parts := make([]string, 3)
	for i, tree := range spend {
		var b strings.Builder
		for _, n := range tree {
			b.WriteByte(byte('0' + n))
		}
		parts[i] = b.String()
		if len(parts[i]) != sizes[i] {
			t.Fatalf("tree %d segment is %d characters, want %d", i, len(parts[i]), sizes[i])
		}
	}
	str := strings.Join(parts, "-")

	msg := &proto.WarriorTalents{}
	core.FillTalentsProto(msg.ProtoReflect(), str, sizes)

	// Read every field back by name and compare with what was spent. A
	// bool field is true iff a point was spent; an int32 carries the count.
	fields := msg.ProtoReflect().Descriptor().Fields()
	if fields.Len() != sizes[0]+sizes[1]+sizes[2] {
		t.Fatalf("WarriorTalents has %d fields, the trees have %d talents", fields.Len(), sizes[0]+sizes[1]+sizes[2])
	}
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		name := string(fd.Name())
		w, ok := want[name]
		if !ok {
			t.Errorf("the message has field %q, which is in no tree", name)
			continue
		}
		v := msg.ProtoReflect().Get(fd)
		switch fd.Kind() {
		case protoreflect.BoolKind:
			if v.Bool() != (w == 1) {
				t.Errorf("%s read back as %v, want %v", name, v.Bool(), w == 1)
			}
		default:
			if int(v.Int()) != w {
				t.Errorf("%s read back as %d, want %d", name, v.Int(), w)
			}
		}
		delete(want, name)
	}
	for name := range want {
		t.Errorf("talent %q has no field in the generated message", name)
	}
}

// repoRoot is where the committed generated files live, relative to this
// package. The regeneration test compares against them, so it has to be
// the checkout and not a copy.
const repoRoot = "../.."

// The generated files in the repository must be exactly what the
// generator writes today. Upstream hand-writes all three of them, and
// PORTING.md now promises that a merge which reintroduces a hand-edited
// <Class>Talents message is silently wrong - this is the test that makes
// that promise enforceable rather than a note. It regenerates all nine
// classes into a temp tree from the checked-in fixtures and compares
// bytes, so a hand edit, a stale `make talents`, or a generator change
// that nobody re-ran fails here instead of passing a reviewer's eye.
//
// It needs no network and no site checkout: the fixtures are the site
// files, and TestFixturesMatchTheSiteData keeps them honest whenever a
// site checkout is present. It needs no protoc either - it compares the
// .proto text, and Task 1's TestGeneratedProtosMatchSources closes the
// remaining link from .proto to .pb.go.
func TestRegeneratingEveryClassIsByteIdentical(t *testing.T) {
	tmp := t.TempDir()
	for _, dir := range []string{"proto", filepath.Join("ui", "core", "talents", "trees")} {
		if err := os.MkdirAll(filepath.Join(tmp, dir), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	for _, slug := range classes {
		if err := os.MkdirAll(filepath.Join(tmp, "sim", slug), 0o755); err != nil {
			t.Fatal(err)
		}
	}

	for _, slug := range classes {
		slug := slug
		t.Run(slug, func(t *testing.T) {
			c := fixtureClass(t, slug)

			// spliceProto edits a .proto in place, so the committed file is
			// the input as well as the expectation: generating into a copy
			// of it must reproduce it exactly, which also proves the splice
			// leaves every other message in the file alone.
			relProto := filepath.Join("proto", slug+".proto")
			committedProto := mustRead(t, filepath.Join(repoRoot, relProto))
			if err := os.WriteFile(filepath.Join(tmp, relProto), []byte(committedProto), 0o644); err != nil {
				t.Fatal(err)
			}

			if err := generateClass(tmp, c); err != nil {
				t.Fatal(err)
			}

			for _, rel := range []string{
				relProto,
				filepath.Join("sim", slug, "talents_auto_gen.go"),
				filepath.Join("ui", "core", "talents", "trees", slug+".json"),
			} {
				want := mustRead(t, filepath.Join(repoRoot, rel))
				got := mustRead(t, filepath.Join(tmp, rel))
				if got != want {
					t.Errorf("%s is not what the generator writes today (%d bytes committed, %d regenerated); run `make talents`.\nfirst difference: %s",
						rel, len(want), len(got), firstDifference(want, got))
				}
			}
		})
	}
}

// The fixtures are copies of the site pipeline's output, and a stale copy
// would make the regeneration test above pin the wrong thing. When a site
// checkout is present, prove they are the same bytes; when it is not, say
// so and skip rather than pretend to have checked.
func TestFixturesMatchTheSiteData(t *testing.T) {
	const siteTalents = "/Users/jh/code/forever/data/builds/1.60.1.69893/talents"
	if _, err := os.Stat(siteTalents); err != nil {
		t.Skipf("no site checkout at %s; the fixtures cannot be compared with their source here", siteTalents)
	}
	for _, slug := range classes {
		want := mustRead(t, filepath.Join(siteTalents, slug+".json"))
		got := mustRead(t, filepath.Join("testdata", slug+".json"))
		if got != want {
			t.Errorf("testdata/%s.json has drifted from %s/%s.json; copy it again", slug, siteTalents, slug)
		}
	}
}

// Every prerequisite in the source has to reach the UI JSON. The picker
// gates spending on prereqLocation (talents_picker.tsx, canSetPoints) and
// draws its arrows from it, so a dropped edge lets a player spend into a
// talent the client would not let them take, silently and with no arrow
// to show what is missing. 69 edges across the nine classes.
func TestUITreeJSONCarriesEveryPrerequisite(t *testing.T) {
	perClass := map[string]int{
		"druid": 9, "hunter": 8, "mage": 6, "paladin": 7, "priest": 8,
		"rogue": 8, "shaman": 7, "warlock": 8, "warrior": 8,
	}
	total, wantTotal := 0, 0
	for _, slug := range classes {
		c := fixtureClass(t, slug)

		// Count the source's edges rather than trusting the table above,
		// then check the table too, so a re-mine that moves an edge fails
		// loudly here instead of quietly agreeing with itself.
		want := 0
		for _, tr := range c.Trees {
			for _, ta := range tr.Talents {
				if ta.PrereqNodeID != 0 {
					want++
				}
			}
		}
		if want != perClass[slug] {
			t.Errorf("%s has %d prerequisite edges in the source, this test expects %d; the data has been re-mined", slug, want, perClass[slug])
		}

		var trees []struct {
			Talents []struct {
				FieldName      string `json:"fieldName"`
				PrereqLocation *struct {
					RowIdx int `json:"rowIdx"`
					ColIdx int `json:"colIdx"`
				} `json:"prereqLocation"`
				PrereqRank int `json:"prereqRank"`
			} `json:"talents"`
		}
		if err := json.Unmarshal([]byte(mustUITreeJSON(t, c)), &trees); err != nil {
			t.Fatalf("%s: the generated UI JSON does not parse: %v", slug, err)
		}
		got := 0
		for i, tr := range trees {
			for _, ta := range tr.Talents {
				if ta.PrereqLocation == nil {
					continue
				}
				got++
				if ta.PrereqRank < 1 {
					t.Errorf("%s/%s has a prerequisite with rank %d", slug, ta.FieldName, ta.PrereqRank)
				}
				// The parent must be a real talent of the same tree, above
				// the child: the picker looks it up by grid position and
				// would throw on a position that holds nothing.
				parent := c.Trees[i].Talents
				found := false
				for _, p := range parent {
					if p.Tier == ta.PrereqLocation.RowIdx && p.Column == ta.PrereqLocation.ColIdx {
						found = true
						if ta.PrereqRank > p.MaxRank {
							t.Errorf("%s/%s requires rank %d of %s, which has %d", slug, ta.FieldName, ta.PrereqRank, p.Name, p.MaxRank)
						}
					}
				}
				if !found {
					t.Errorf("%s/%s points at row %d col %d, where the %s tree has no talent",
						slug, ta.FieldName, ta.PrereqLocation.RowIdx, ta.PrereqLocation.ColIdx, c.Trees[i].Name)
				}
			}
		}
		if got != want {
			t.Errorf("%s: the UI JSON carries %d prerequisites, the source has %d", slug, got, want)
		}
		total += got
		wantTotal += want
	}
	if wantTotal != 69 {
		t.Errorf("the source has %d prerequisite edges in total, want 69", wantTotal)
	}
	if total != 69 {
		t.Errorf("the generated UI JSON carries %d prerequisite edges in total, want 69", total)
	}
}

