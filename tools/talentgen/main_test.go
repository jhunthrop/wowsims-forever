// The generator writes gofmt-canonical Go on its own, so `go run
// ./tools/talentgen` without the make target's formatting step does not
// leave nine unformatted files behind.
func TestGoFileIsAlreadyFormatted(t *testing.T) {
	for _, slug := range classes {
		src := mustGoFile(t, fixtureClass(t, slug))
		formatted, err := format.Source([]byte(src))
		if err != nil {
			t.Fatalf("%s: %v", slug, err)
		}
		if string(formatted) != src {
			t.Errorf("%s: goFile output is not gofmt-canonical", slug)
		}
	}
}

func mustRead(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// firstDifference names the first line that differs, so a byte-identity
// failure reads as "this line changed" rather than as two large blobs.
func firstDifference(want, got string) string {
	w, g := strings.Split(want, "\n"), strings.Split(got, "\n")
	for i := 0; i < len(w) || i < len(g); i++ {
		var wl, gl string
		if i < len(w) {
			wl = w[i]
		}
		if i < len(g) {
			gl = g[i]
		}
		if wl != gl {
			return fmt.Sprintf("line %d: committed %q, regenerated %q", i+1, wl, gl)
		}
	}
	return "the files differ only in trailing bytes"
}
